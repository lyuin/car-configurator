import type { Point } from './geometry';
import type { Silhouette } from './types';

/**
 * 側面図の形状をシルエット別に定義する。
 *
 * 座標は正規化値で、x は全長比（0 = 前端バンパー、1 = 後端バンパー）、
 * y は全高比（0 = 地面、1 = ルーフ）。実寸への展開は `buildSideView` が行う。
 *
 * 名前付きパラメータを並べるのではなく点列で持つのは、描画結果を見ながら
 * 数値を直接いじって形を追い込めるようにするため。
 */
export interface SideProfile {
  /** 上面の輪郭。前端フェイスの上端から後端フェイスの上端まで */
  readonly upper: readonly Point[];
  /** グリーンハウス（窓まわり）の閉じた輪郭 */
  readonly greenhouse: readonly Point[];
  /** ドア分割線を引く x。ベルトラインからサイドシルまで引く */
  readonly doorLines: readonly number[];
  /** ベルトライン（窓下端）の高さ */
  readonly beltline: number;
  /**
   * ホイールアーチの半径倍率（タイヤ半径に対する比）。既定 1.12。
   * 大きいほど四駆的に角ばったアーチ、小さいほどタイヤに沿ったアーチになる。
   * SUV とワゴンのように上面輪郭が近いシルエットを描き分ける手がかりになる。
   */
  readonly archRatio?: number;
  /**
   * 下部クラッディング（樹脂プロテクター）の高さ。全高比。
   * SUV・ピックアップの識別に効くため、該当シルエットにのみ指定する。
   */
  readonly claddingY?: number;
}

